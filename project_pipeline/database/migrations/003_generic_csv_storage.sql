-- =====================================================================
-- Migration 003: Generic CSV Data and Rejection Audit Storage
-- Purpose: Additive, idempotent tables for storing arbitrary CSV row payloads
--          and row-level rejection audit trails.
-- =====================================================================

CREATE TABLE IF NOT EXISTS pipeline_generic_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id INTEGER REFERENCES pipeline_execution(execution_id) ON DELETE CASCADE,
    pipeline_name VARCHAR(100) NOT NULL,
    row_number INTEGER NOT NULL,
    data JSONB NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_generic_data_execution_id
    ON pipeline_generic_data(execution_id);
CREATE INDEX IF NOT EXISTS idx_generic_data_pipeline_name
    ON pipeline_generic_data(pipeline_name);

CREATE TABLE IF NOT EXISTS pipeline_rejected_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id INTEGER REFERENCES pipeline_execution(execution_id) ON DELETE CASCADE,
    pipeline_name VARCHAR(100) NOT NULL,
    row_number INTEGER NOT NULL,
    raw_data JSONB,
    rejection_reasons JSONB NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_rejected_rows_execution_id
    ON pipeline_rejected_rows(execution_id);
CREATE INDEX IF NOT EXISTS idx_rejected_rows_pipeline_name
    ON pipeline_rejected_rows(pipeline_name);
